from __future__ import annotations

import os
import re
from datetime import datetime
from typing import Annotated, Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel

from api.pathsafe import BGM_PATH_ERROR, resolve_bgm_file
from orchestrator.db import get_db, init_db
from orchestrator.models import Asset, PublishRecord, ShotTask, VideoTask
from orchestrator.queue.manager import QueueManager
from orchestrator.review.manager import ReviewManager

router = APIRouter(prefix="/orchestrator", tags=["orchestrator"])

_DB_PATH = os.environ.get("ORCHESTRATOR_DB_PATH", "orchestrator.db")


async def init_orchestrator_db() -> None:
    """Create the orchestrator tables if they do not exist yet.

    Called from the API lifespan so that a fresh service (no database file)
    answers the orchestrator routes instead of failing with
    ``no such table``. ``init_db`` only runs ``CREATE TABLE IF NOT EXISTS``,
    so calling it on every start-up is safe.
    """
    await init_db(_DB_PATH)


# Task ids are generated by the server (UUID strings). They become part of
# file paths (output/exports/<task_id>/), so a task_id path parameter must be
# one plain segment: letters, digits, "-" and "_" only.
_TASK_ID = re.compile(r"[A-Za-z0-9_-]{1,64}")
_TASK_NOT_FOUND = "Task not found"


def _checked_task_id(task_id: str) -> str:
    """Answer 404 for a task_id that cannot be a task id; no lookup is done."""
    if not _TASK_ID.fullmatch(task_id):
        raise HTTPException(status_code=404, detail=_TASK_NOT_FOUND)
    return task_id


TaskId = Annotated[str, Depends(_checked_task_id)]


def _queue() -> QueueManager:
    return QueueManager(_DB_PATH)


def _review() -> ReviewManager:
    return ReviewManager(_DB_PATH)


class CreateVideoTaskRequest(BaseModel):
    title: str
    script: str
    style_pack_id: Optional[str] = None
    character_pack_id: Optional[str] = None


class ShotPayload(BaseModel):
    shot_index: int
    prompt: str
    duration: float = 5.0
    aspect_ratio: str = "9:16"


class CreateShotsRequest(BaseModel):
    shots: list[ShotPayload]


class RejectShotRequest(BaseModel):
    new_prompt: Optional[str] = None


class PublishRequest(BaseModel):
    title: str
    description: str = ""
    tags: list[str] = []
    privacy: str = "private"
    bgm_path: Optional[str] = None


@router.post("/tasks", status_code=201)
async def create_video_task(req: CreateVideoTaskRequest):
    task = VideoTask(
        title=req.title,
        script=req.script,
        style_pack_id=req.style_pack_id,
        character_pack_id=req.character_pack_id,
    )
    return await _queue().create_video_task(task)


@router.get("/tasks")
async def list_video_tasks():
    return await _queue().list_video_tasks()


@router.get("/tasks/{task_id}")
async def get_video_task(task_id: TaskId):
    task = await _queue().get_video_task(task_id)
    if not task:
        raise HTTPException(status_code=404, detail=_TASK_NOT_FOUND)
    return task


@router.post("/tasks/{task_id}/shots", status_code=201)
async def create_shots(task_id: TaskId, req: CreateShotsRequest):
    queue = _queue()
    if await queue.get_video_task(task_id) is None:
        raise HTTPException(status_code=404, detail=_TASK_NOT_FOUND)
    shots = [
        ShotTask(
            video_task_id=task_id,
            shot_index=s.shot_index,
            prompt=s.prompt,
            duration=s.duration,
            aspect_ratio=s.aspect_ratio,
        )
        for s in req.shots
    ]
    return await queue.create_shots(shots)


@router.get("/tasks/{task_id}/shots")
async def get_shots(task_id: TaskId):
    return await _queue().get_shots_by_video(task_id)


@router.post("/tasks/{task_id}/review/approve")
async def approve_video(task_id: TaskId):
    await _review().approve_video(task_id)
    return {"ok": True}


@router.post("/shots/{shot_id}/approve")
async def approve_shot(shot_id: str):
    await _review().approve_shot(shot_id)
    return {"ok": True}


@router.post("/shots/{shot_id}/reject")
async def reject_shot(shot_id: str, req: RejectShotRequest):
    await _review().reject_shot(shot_id, new_prompt=req.new_prompt)
    return {"ok": True}


@router.post("/tasks/{task_id}/publish")
async def publish_task(task_id: TaskId, req: PublishRequest):
    from orchestrator.assets.manager import AssetManager
    from orchestrator.publish.composer import compose_video
    from orchestrator.publish.youtube import VideoMeta, upload_to_youtube

    # Validate the request before any work; ffmpeg only gets the resolved path.
    bgm_file = None
    if req.bgm_path:
        bgm_file = resolve_bgm_file(req.bgm_path)
        if bgm_file is None:
            raise HTTPException(status_code=400, detail=BGM_PATH_ERROR)

    queue = _queue()
    shots = await queue.get_shots_by_video(task_id)
    approved = sorted(
        [s for s in shots if s.status == "approved"],
        key=lambda s: s.shot_index,
    )
    if not approved:
        raise HTTPException(status_code=400, detail="No approved shots")

    asset_mgr = AssetManager(_DB_PATH)
    clip_paths = []
    for shot in approved:
        assets = await asset_mgr.get_by_shot(shot.id)
        clips = [a for a in assets if a.type == "video_clip"]
        if not clips:
            raise HTTPException(
                status_code=400,
                detail=f"Shot {shot.shot_index} has no video_clip asset",
            )
        clip_paths.append(clips[-1].file_path)

    output_path = f"output/exports/{task_id}/final.mp4"
    await compose_video(
        clip_paths=clip_paths,
        output_path=output_path,
        bgm_path=str(bgm_file) if bgm_file else None,
    )

    export_asset = Asset(task_id=task_id, type="export", file_path=output_path)
    await asset_mgr.register(export_asset)

    meta = VideoMeta(
        title=req.title,
        description=req.description,
        tags=req.tags,
        privacy=req.privacy,
    )
    video_id = await upload_to_youtube(output_path, meta)

    record = PublishRecord(
        video_task_id=task_id,
        platform="youtube",
        platform_video_id=video_id,
        url=f"https://www.youtube.com/watch?v={video_id}",
        status="published",
        published_at=datetime.utcnow().isoformat(),
    )
    async with get_db() as conn:
        await conn.execute(
            """INSERT INTO publish_records
               (id, video_task_id, platform, platform_video_id, url, status, published_at)
               VALUES (?,?,?,?,?,?,?)""",
            (record.id, record.video_task_id, record.platform,
             record.platform_video_id, record.url, record.status, record.published_at),
        )
        await conn.commit()
    await queue.update_video_task(task_id, status="published")
    return {"youtube_url": record.url, "video_id": video_id}
